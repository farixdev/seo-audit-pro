# -*- coding: utf-8 -*-
"""
Create a small demo organization in a LOCAL development database.

  set SEO_DB=sqlite
  .venv/Scripts/python.exe scripts/dev_seed.py

Refuses to run against PostgreSQL (production). Generated passwords are written
to server_data/dev_credentials.txt (git-ignored) — never into source control.
No leads, audits or scores are fabricated: add real websites and run real
audits from the app.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from backend import config, db, migrations, security  # noqa: E402
from backend.util import now_iso  # noqa: E402


def main():
    if db.DIALECT != "sqlite":
        sys.exit("dev_seed only runs against the local SQLite development database. Set SEO_DB=sqlite.")
    migrations.migrate()
    if (db.scalar("SELECT COUNT(*) FROM users") or 0) > 0:
        sys.exit("The development database already has users. Delete server_data/seo_audit_pro.db to start over.")
    now = now_iso()
    teams = {}
    for name in ("Growth", "Local SEO"):
        tid = security.new_id("team_")
        db.execute("INSERT INTO teams (id, name, name_key, created_at, updated_at) VALUES (%s, %s, %s, %s, %s)",
                   (tid, name, name.lower(), now, now))
        teams[name] = tid
    people = [("Morgan Hale", "manager@dev.local", "MANAGER", None),
              ("Riley Chen", "lead.growth@dev.local", "TEAM_LEAD", "Growth"),
              ("Sam Ortiz", "agent.growth@dev.local", "AGENT", "Growth"),
              ("Jordan Blake", "lead.local@dev.local", "TEAM_LEAD", "Local SEO"),
              ("Avery Quinn", "agent.local@dev.local", "AGENT", "Local SEO"),
              ("Casey Park", "new.agent@dev.local", "AGENT", "Growth")]
    lines = ["# Local development accounts (generated by scripts/dev_seed.py). Not for production.", ""]
    for name, email, role, team in people:
        pw = security.generate_temporary_password()
        must_change = 1 if email.startswith("new.") else 0
        db.execute("""INSERT INTO users (id, name, email, password_hash, role, team_id, is_active, must_change_password,
                      created_at, updated_at) VALUES (%s, %s, %s, %s, %s, %s, 1, %s, %s, %s)""",
                   (security.new_id("usr_"), name, email, security.hash_password(pw), role, teams.get(team),
                    must_change, now, now))
        lines.append(f"{role:<10} {email:<26} {pw}" + ("   (must change at first sign-in)" if must_change else ""))
    path = os.path.join(config.DATA_DIR, "dev_credentials.txt")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Seeded {len(people)} users in 2 teams. Credentials written to {path}")


if __name__ == "__main__":
    main()
