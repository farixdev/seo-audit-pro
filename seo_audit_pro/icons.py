@lru_cache(maxsize=512)
def _pixmap(name, color, size, dpr, stroke):
    body = _P.get(name) or _P["file"]
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    px = QPixmap(int(size * dpr), int(size * dpr))
    px.fill(Qt.GlobalColor.transparent)
    p = QPainter(px)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(p, QRectF(0, 0, size * dpr, size * dpr))
    p.end()
    px.setDevicePixelRatio(dpr)
    return px


def _dpr():
    app = QGuiApplication.instance()
    screen = app.primaryScreen() if app else None
    return max(1.0, screen.devicePixelRatio() if screen else 1.0)


def pixmap(name, color="#52525B", size=16, stroke=1.75):
    return _pixmap(name, QColor(color).name(), size, _dpr(), stroke)


def icon(name, color="#52525B", size=16, active_color=None, stroke=1.75):
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size, stroke), QIcon.Mode.Normal, QIcon.State.Off)
    ic.addPixmap(pixmap(name, "#A1A1AA", size, stroke), QIcon.Mode.Disabled, QIcon.State.Off)
    if active_color:
        ic.addPixmap(pixmap(name, active_color, size, stroke), QIcon.Mode.Active, QIcon.State.Off)
        ic.addPixmap(pixmap(name, active_color, size, stroke), QIcon.Mode.Selected, QIcon.State.Off)
    return ic


def qsize(n):
    return QSize(n, n)


